LIQUID_SIZES = [
    ("২৫০ মিলি", 0.5), ("৫০০ মিলি", 1.0), ("১ লিটার", 1.8),
    ("২ লিটার", 3.2), ("৫ লিটার", 7.0),
]

LIQUID_CATS = {"রান্নার তেল", "পানীয়", "স্টক ও সস", "রান্নার উপাদান"}


def generate_products(target: int = 5000) -> list[dict]:
    """Generate products by combining base products × brands × sizes."""
    products = []
    prod_id = 0

    # Shuffle brands for variety
    brand_pool = BRANDS * 20  # enough for all combos

    for cat_name, items in CATEGORIES.items():
        sizes = LIQUID_SIZES if cat_name in LIQUID_CATS else SIZES
        for base_name, base_desc, base_price in items:
            # Generate multiple brand × size variants per base product
            for brand in random.sample(BRANDS, min(len(BRANDS), 5)):
                for size_label, price_mult in random.sample(sizes, min(len(sizes), 3)):
                    price = int(base_price * price_mult * random.uniform(0.9, 1.1))
                    price = max(10, price)  # minimum ৳10

                    name = f"{brand} {base_name} {size_label}"
                    desc = f"{base_desc}, {size_label}, {brand} ব্র্যান্ড"

                    products.append({
                        "id": f"prod_{prod_id:05d}",
                        "name": name,
                        "category": cat_name,
                        "description": desc,
                        "price_taka": price,
                    })
                    prod_id += 1

                    if prod_id >= target:
                        return products

    # If we haven't hit target, add more variations with random price jitter
    while prod_id < target:
        cat_name = random.choice(list(CATEGORIES.keys()))
        base_name, base_desc, base_price = random.choice(CATEGORIES[cat_name])
        brand = random.choice(BRANDS)
        sizes = LIQUID_SIZES if cat_name in LIQUID_CATS else SIZES
        size_label, price_mult = random.choice(sizes)
        price = int(base_price * price_mult * random.uniform(0.85, 1.15))
        price = max(10, price)

        products.append({
            "id": f"prod_{prod_id:05d}",
            "name": f"{brand} {base_name} ({size_label})",
            "category": cat_name,
            "description": f"{base_desc}, {size_label}, {brand} ব্র্যান্ড, প্রিমিয়াম কোয়ালিটি",
            "price_taka": price,
        })
        prod_id += 1

    return products


MOCK_PRODUCTS = generate_products(5000)


