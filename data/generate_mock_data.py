def generate_csv(output_path: str = "data/products.csv") -> str:
    """Generate mock product dataset as CSV."""
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)

    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["id", "name", "category", "description", "price_taka"])
        writer.writeheader()
        writer.writerows(MOCK_PRODUCTS)

    return str(path)


def generate_json(output_path: str = "data/products.json") -> str:
    """Generate mock product dataset as JSON."""
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)

    with open(path, "w", encoding="utf-8") as f:
        json.dump(MOCK_PRODUCTS, f, ensure_ascii=False, indent=2)

    return str(path)


